def glyph(ch):
    if ch in GLYPHS:
        return GLYPHS[ch]
    if ch.upper() in GLYPHS:
        return GLYPHS[ch.upper()]
    return GLYPHS["?"]


def draw_text(cv, x, y, text, color, sx=1, sy=1, spacing=1):
    """以 5×7 字形畫字，sx/sy 為整數放大倍率。回傳畫完後的 x。"""
    for ch in text:
        g = glyph(ch)
        for j, row in enumerate(g):
            for i, b in enumerate(row):
                if b == "#":
                    cv.rect(x + i * sx, y + j * sy, sx, sy, color)
        x += (5 + spacing) * sx
    return x


def text_width(text, sx=1, spacing=1):
    return len(text) * (5 + spacing) * sx - spacing * sx


# --- 繪圖輔助 -----------------------------------------------------------------

def from_map(rows, legend):
    """ASCII 像素圖轉 Canvas。'.' 與空白為透明。"""
    h = len(rows)
    w = max(len(r) for r in rows)
    cv = Canvas(w, h)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in ".  ":
                continue
            cv.set(x, y, legend[ch])
    return cv


def add_outline(cv, color=OUTLINE, diagonal=False, x0=0, y0=0, w=None, h=None):
    """在不透明像素周圍（限定區域內）的透明像素補上外框。"""
    w = cv.w if w is None else w
    h = cv.h if h is None else h
    nb = [(1, 0), (-1, 0), (0, 1), (0, -1)]
    if diagonal:
        nb += [(1, 1), (1, -1), (-1, 1), (-1, -1)]
    todo = []
    for y in range(y0, y0 + h):
        for x in range(x0, x0 + w):
            if cv.get(x, y)[3] != 0:
                continue
            for dx, dy in nb:
                nx, ny = x + dx, y + dy
                if x0 <= nx < x0 + w and y0 <= ny < y0 + h and cv.get(nx, ny)[3] != 0 and cv.get(nx, ny) != color:
                    todo.append((x, y))
                    break
    for x, y in todo:
        cv.set(x, y, color)


def recolor(cv, mapping):
    out = Canvas(cv.w, cv.h)
    for i, p in enumerate(cv.px):
        out.px[i] = mapping.get(p, p)
    return out


def flip_h(cv):
    out = Canvas(cv.w, cv.h)
    for y in range(cv.h):
        for x in range(cv.w):
            out.px[y * cv.w + x] = cv.px[y * cv.w + (cv.w - 1 - x)]
    return out


def flip_v(cv):
    out = Canvas(cv.w, cv.h)
    for y in range(cv.h):
        out.px[y * cv.w:(y + 1) * cv.w] = cv.px[(cv.h - 1 - y) * cv.w:(cv.h - y) * cv.w]
    return out


def crop(cv, x, y, w, h):
    out = Canvas(w, h)
    for j in range(h):
        for i in range(w):
            out.px[j * w + i] = cv.get(x + i, y + j)
    return out


def scale(cv, k):
    out = Canvas(cv.w * k, cv.h * k)
    for y in range(out.h):
        sy = y // k
        for x in range(out.w):
            out.px[y * out.w + x] = cv.px[sy * cv.w + x // k]
    return out


def hash2(x, y, seed=0):
    """決定性的 0–1 雜湊，用來撒點，不依賴 random 狀態。"""
    n = (x * 374761393 + y * 668265263 + seed * 2147483647) & 0xFFFFFFFF
    n = ((n ^ (n >> 13)) * 1274126177) & 0xFFFFFFFF
    n ^= n >> 16
    return (n & 0xFFFF) / 65535.0


def wrap_noise(x, y, period, seed=0, cell=16):
    """水平方向以 period 循環的平滑值雜訊（0–1）。period 必須是 cell 的倍數。"""
    gx0 = math.floor(x / cell)
    gy0 = math.floor(y / cell)
    fx = x / cell - gx0
    fy = y / cell - gy0
    n = period // cell

    def v(gx, gy):
        return hash2(gx % n, gy, seed)

    def s(t):
        return t * t * (3 - 2 * t)
    a = v(gx0, gy0) + (v(gx0 + 1, gy0) - v(gx0, gy0)) * s(fx)
    b = v(gx0, gy0 + 1) + (v(gx0 + 1, gy0 + 1) - v(gx0, gy0 + 1)) * s(fx)
    return a + (b - a) * s(fy)


BAYER4 = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def dither(x, y, t):
    """t 在 0–1，回傳此像素是否該取較亮的色（4×4 Bayer）。"""
    return t * 16 > BAYER4[y % 4][x % 4] + 0.5
